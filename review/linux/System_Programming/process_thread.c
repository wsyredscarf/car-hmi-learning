/*
    IPC（进程间通信） ：六大通信-----（管道（无名管道（pipe）、有名管道（FIFO）），消息队列，共享内存，信号，信号，套接字（通常用于不同主机之间的通信，但是本地通信也可以）
1、管道（pipe）
管道分为无名管道（父子进程）和命名管道（FIFO）（无亲缘关系进程），字节流形式传输数据。
 ##无名管道：
    int main() {
        int fd[2];  // fd[0]读端, fd[1]写端
        if (pipe(fd) < 0) { perror("pipe"); return -1; }

        pid_t pid = fork();
        if (pid == 0) {
            // 子进程：写数据
            close(fd[0]);          // 关闭不用的读端（关键：不关会导致读端永远等不到EOF）
            write(fd[1], "hello", 5);
            close(fd[1]);
        } else {
            // 父进程：读数据
            close(fd[1]);          // 关闭不用的写端
            char buf[32] = {0};
            read(fd[0], buf, sizeof(buf));
            printf("parent recv: %s\n", buf);
            close(fd[0]);
            wait(NULL);            // 回收子进程
        }
        return 0;
    }
    关键点：
        只能用于亲缘关系进程（父子、兄弟）。
        半双工，同一时刻单向传输。
        read 端在写端全部关闭后，read 返回 0（EOF）。
        写端关闭后，读端 read 返回0；读端关闭，写端 write 会触发 SIGPIPE 信号，默认进程终止。

  ##有名管道：
    // 写进程
    int fd = open("/tmp/myfifo", O_WRONLY);
    write(fd, "hello", 5);
    close(fd);

    // 读进程
    int fd = open("/tmp/myfifo", O_RDONLY);
    char buf[32];
    read(fd, buf, sizeof(buf));
    close(fd);

    关键点：
        需要特殊的管道文件路径
        open FIFO时，如果以只读打开会阻塞，直到有写端打开；以只写打开也会阻塞，直到有读端打开（可以加 O_NONBLOCK 改为非阻塞）。

2、消息队列（Message Queue）
// ##必须定义消息结构体，第一个成员必须是 long 类型的 mtype
    struct msgbuf {
        long mtype;       // 消息类型，必须 > 0
        char mtext[128];  // 消息内容
    };

    int main() {
        // 1. 创建消息队列
        int msqid = msgget(IPC_PRIVATE, IPC_CREAT | 0666);
        if (msqid < 0) { perror("msgget"); return -1; }

        // 2. 发送消息
        struct msgbuf msg;
        msg.mtype = 1;
        strcpy(msg.mtext, "hello mq");
        msgsnd(msqid, &msg, strlen(msg.mtext) + 1, 0);

        // 3. 接收消息（按类型接收）
        struct msgbuf rcv;
        msgrcv(msqid, &rcv, sizeof(rcv.mtext), 1, 0);
        printf("recv: %s\n", rcv.mtext);

        // 4. 删除消息队列
        msgctl(msqid, IPC_RMID, NULL);
        return 0;
    }
    关键点：
        消息有边界，不像管道是字节流。
        可以通过 mtype 按类型读取，读取特定类型的数据。
        生命周期随内核，必须显式调用 msgctl(IPC_RMID) 删除，否则一直存在。
        适用于结构化的数据传递。
*/

/*
3、共享内存（Shared Memory）
    int main() {
        // 1. 创建共享内存（size = 1024）
        int shmid = shmget(IPC_PRIVATE, 1024, IPC_CREAT | 0666);
        if (shmid < 0) { perror("shmget"); return -1; }

        // 2. 映射到当前进程地址空间
        char *addr = (char *)shmat(shmid, NULL, 0);

        // 3. 读写共享内存
        strcpy(addr, "hello shared memory");
        printf("%s\n", addr);

        // 4. 解除映射
        shmdt(addr);

        // 5. 删除共享内存
        shmctl(shmid, IPC_RMID, NULL);
        return 0;
    }
    关键点：
        速度最快的IPC方式。数据直接在内存中共享，不需要内核两次拷贝。
        本身不提供同步机制！如果多个进程同时读写，必须配合信号量或互斥锁使用。
        shmdt 只是解除映射，shmctl(IPC_RMID) 才是真正删除。
        权限控制：需检查 shmat 返回值，失败返回 (void *)-1。
*/

/*
4、信号量（Semaphore）
    ##POSIX标准信号量，常用于同步与互斥。
    int main() {
        // 1. 打开或创建命名信号量（用于进程间）
        sem_t *sem = sem_open("/mysem", O_CREAT, 0644, 1);
        if (sem == SEM_FAILED) { perror("sem_open"); return -1; }

        // 2. P操作（等待，减1）
        sem_wait(sem);  // 若值为0则阻塞

        // 3. 临界区
        printf("enter critical section\n");

        // 4. V操作（释放，加1）
        sem_post(sem);

        // 5. 关闭和删除
        sem_close(sem);
        sem_unlink("/mysem");
        return 0;
    }
    关键点：
        信号量是同步工具，不传输数据。
        互斥锁（Mutex）有所有权，谁锁谁解；信号量无所有权，任何进程都能 post。
        共享内存 + 信号量 = 完整的进程间数据同步解决方案。
        P操作（wait）可能阻塞，V操作（post）唤醒。
*/

/*
5、信号（Signal
  ##信号处理函数
    void sig_handler(int sig) {
        if (sig == SIGUSR1) {
            printf("received SIGUSR1\n");
        }
    }

    int main() {
        // 1. 注册信号处理函数
        signal(SIGUSR1, sig_handler);  // 也可以用 sigaction

        // 2. 发送信号给自身
        raise(SIGUSR1);

        // 3. 发送信号给其他进程（kill）
        // kill(pid, SIGUSR1);

        pause();  // 挂起，等待信号
        return 0;
    }
    关键点：
        异步通知，信息量少（只传一个整数）。
        常见信号：SIGINT（Ctrl+C）、SIGKILL（不可捕获）、SIGPIPE、SIGCHLD。
        实际应用中，常用 SIGCHLD 通知父进程回收子进程；SIGPIPE 通常忽略（signal(SIGPIPE, SIG_IGN)）。
        信号处理函数要尽量简短，只做置标志或发信号量，不要做耗时操作。
*/

